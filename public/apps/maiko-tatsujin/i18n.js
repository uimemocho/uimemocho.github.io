export function detectLang() {
  const saved = (() => { try { return localStorage.getItem('maiko.lang'); } catch { return null; } })();
  if (saved && T[saved]) return saved;
  const n = (navigator.language || 'ja').toLowerCase();
  if (n.startsWith('zh')) return /tw|hk|mo|hant/.test(n) ? 'zh-Hant' : 'zh-Hans';
  for (const [k] of LANGS) if (n.startsWith(k.toLowerCase())) return k;
  return 'en';
}
export function setLang(l) { current = T[l] ? l : 'ja'; document.documentElement.lang = current; try { localStorage.setItem('maiko.lang', current); } catch {} }
export function getLang() { return current; }
export function t(key, vars) {
  let s = (T[current] && T[current][key]) ?? T.ja[key] ?? key;
  if (vars) for (const k in vars) s = s.replaceAll('{' + k + '}', vars[k]);
  return s;
}
export function applyI18n(rootEl = document) {
  rootEl.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  rootEl.querySelectorAll('[data-i18n-ph]').forEach(el => { el.placeholder = t(el.dataset.i18nPh); });
  rootEl.querySelectorAll('[data-i18n-aria]').forEach(el => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
}
